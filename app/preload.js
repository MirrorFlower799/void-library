'use strict';

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('voidLibrary', {
  load: () => ipcRenderer.invoke('data:load'),
  save: (games) => ipcRenderer.invoke('data:save', games),
  exportData: () => ipcRenderer.invoke('data:export'),
  importData: () => ipcRenderer.invoke('data:import'),
  previewImport: () => ipcRenderer.invoke('data:import-preview'),
  applyImport: (p) => ipcRenderer.invoke('data:import-apply', p),
  dataDir: () => ipcRenderer.invoke('data:dir'),
  loadSettings: () => ipcRenderer.invoke('settings:load'),
  saveSettings: (s) => ipcRenderer.invoke('settings:save', s),
  loadCharacters: () => ipcRenderer.invoke('characters:load'),
  saveCharacters: (list) => ipcRenderer.invoke('characters:save', list),
  translate: (p) => ipcRenderer.invoke('translate:text', p),
  scrapeSearch: (p) => ipcRenderer.invoke('scrape:search', p),
  scrapeAssets: (p) => ipcRenderer.invoke('scrape:assets', p),
  downloadImage: (p) => ipcRenderer.invoke('scrape:download', p),
  importShotsFolder: (gameId) => ipcRenderer.invoke('shots:import-folder', gameId),
  importCharsFolder: () => ipcRenderer.invoke('chars:import-folder'),
  fetchChars: (p) => ipcRenderer.invoke('chars:fetch', p),
  searchWorks: (p) => ipcRenderer.invoke('chars:search-works', p),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  loadArts: () => ipcRenderer.invoke('arts:load'),
  saveArts: (list) => ipcRenderer.invoke('arts:save', list),
  artOpen: (p) => ipcRenderer.invoke('art:open', p),
  artReveal: (p) => ipcRenderer.invoke('art:reveal', p),
  pickArtFile: () => ipcRenderer.invoke('art:pick-file'),
  pickArtFolder: () => ipcRenderer.invoke('art:pick-folder'),
  artBrowse: (p) => ipcRenderer.invoke('art:browse', p),
  artCover: (p) => ipcRenderer.invoke('art:cover', p),
  bookOpen: (p) => ipcRenderer.invoke('book:open', p),
  libLoad: () => ipcRenderer.invoke('lib:load'),
  libSave: (lib) => ipcRenderer.invoke('lib:save', lib),
  libCover: (p) => ipcRenderer.invoke('lib:cover', p),
  libReadText: (p) => ipcRenderer.invoke('lib:read-text', p),
  libImportFiles: (shelfId) => ipcRenderer.invoke('lib:import-files', shelfId),
  libImportFolder: (shelfId) => ipcRenderer.invoke('lib:import-folder', shelfId),
  onImportProgress: (cb) => ipcRenderer.on('lib:import-progress', (_e, p) => cb(p)),
  libDeleteFiles: (ids) => ipcRenderer.invoke('lib:delete-files', ids),
  libImageList: (p) => ipcRenderer.invoke('lib:image-list', p),
  openShotsFolder: (gameId) => ipcRenderer.invoke('shots:open-folder', gameId)
});
